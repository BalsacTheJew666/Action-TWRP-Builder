#!/usr/bin/env python3
"""READ-ONLY Motorola nevada stock module export-name provider attribution.

Input: the PRIVATE local JSON generated by nevada-stock-vendor-kmi-import-inventory.py.
Find on-disk .ko files and examine their ELF __ksymtab_strings exports, and
optionally root-visible /proc/kallsyms __ksymtab_ names. This resolves possible
module-provider names for imports not in the official GKI vmlinux.symvers.

Critical: an export name in a module does NOT prove provider CRC equality, that
the file is loaded, or which other module provides it. A __ksymtab name visible
in kallsyms may belong to a loaded module or built-in vmlinux; this audit does
not infer kernel ownership without actual evidence. NO install authorization.

Nothing is uploaded or modified on Android. Python only reads /proc and already
existing .ko files; the local JSON report is created with mode 0600.
"""
import argparse
from collections import defaultdict
from datetime import datetime,timezone
import importlib.util
import json
import os
from pathlib import Path
import re
import struct
import sys

EXPECTED_KERNEL="5.15.180-android13-8-00018-g9b2308ac0ad6-ab14563692"
GKI_EXPORT_COUNT=8471
REMAINING=("usb_get_urb","rfkill_pause_polling")

def load_module_inventory_helper(path):
    spec=importlib.util.spec_from_file_location("nv_existing_stock_inventory",str(path))
    if not spec or not spec.loader:
        raise RuntimeError("Cannot import local source-only stock inventory")
    module=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    for needed in ("load_witness","paths_from_user","paths_from_root","DIRS"):
        if not hasattr(module,needed):
            raise RuntimeError(f"Stock inventory helper lacks {needed}")
    return module

def elf_sections(data):
    if len(data)<64 or data[:6]!=b"\x7fELF\x02\x01":
        return {}
    section_offset=struct.unpack_from("<Q",data,40)[0]
    entsize,section_count,names_index=struct.unpack_from("<HHH",data,58)
    if entsize!=64 or not section_count or section_count>8192:
        return {}
    if names_index>=section_count or section_offset+entsize*section_count>len(data):
        return {}
    headers=[struct.unpack_from("<IIQQQQIIQQ",data,section_offset+i*entsize)
             for i in range(section_count)]
    h=headers[names_index]
    if h[4]+h[5]>len(data):
        return {}
    names=data[h[4]:h[4]+h[5]]
    result={}
    for h in headers:
        if h[0]>=len(names) or h[4]+h[5]>len(data):
            continue
        section=names[h[0]:].split(b"\x00",1)[0].decode("ascii","replace")
        if section:
            result[section]=data[h[4]:h[4]+h[5]]
    return result

def module_export_strings(data):
    """Evidence: known kernel export strings within an ELF __ksymtab_strings.

    Some vendor-built modules may be stripped or use different layouts.
    The absence of this section is NOT proof they export nothing.
    """
    sections=elf_sections(data)
    if "__ksymtab_strings" not in sections:
        return set(),False
    raw=sections["__ksymtab_strings"]
    if len(raw)>16_000_000:
        return set(),False
    names=set()
    for item in raw.split(b"\x00"):
        if not item or len(item)>512:
            continue
        try:
            symbol=item.decode("ascii")
        except UnicodeError:
            continue
        if re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*",symbol):
            names.add(symbol)
    return names,True

def observed_export_names_from_kallsyms(read_func):
    raw=read_func("/proc/kallsyms")
    if not raw:
        return set(),False
    names=set()
    has_any=False
    for line in raw.splitlines():
        parts=line.split()
        if len(parts)<3:
            continue
        name=parts[2].decode("ascii","replace")
        if name.startswith("__ksymtab_"):
            has_any=True
            names.add(name[len("__ksymtab_"):])
    return names,has_any

def run(args):
    inventory=json.loads(args.stock_import_report.read_text())
    if inventory.get("mode")!="android_normal_boot_disk_modules" and args.offline_dir is None:
        raise RuntimeError("Not a normal-boot stock import report")
    if inventory.get("public_gki_core_export_count")!=GKI_EXPORT_COUNT and args.offline_dir is None:
        raise RuntimeError("Wrong official GKI baseline, require 8471 public exports")
    imports={}
    for row in inventory.get("symbol_records",[]):
        sym=row["symbol"]
        if sym in imports:
            raise RuntimeError("Duplicate stock import name: "+sym)
        if any(it["category"]=="not_in_public_gki" for it in row["imported_versions"]):
            imports[sym]=row
    if args.offline_dir is None and len(imports)!=1119:
        raise RuntimeError(f"Expected previous stock audit 1119 non-GKI symbol names; found {len(imports)}")
    helper=load_module_inventory_helper(args.stock_inventory_script)
    witness=helper.load_witness()
    if args.offline_dir:
        paths={str(x) for x in args.offline_dir.rglob("*.ko")}
    else:
        plain=helper.paths_from_user(helper.DIRS)
        rooted,root_meta=helper.paths_from_root(helper.DIRS)
        paths=plain|rooted
        if not paths:
            raise RuntimeError("No read-only on-disk modules could be discovered")
    groups=defaultdict(list)
    for path in paths:
        name=Path(path).name
        if name.endswith(".ko"):
            groups[name[:-3].replace("-","_")].append(Path(path))
    providers=defaultdict(set)
    no_ksymtab=[]
    discarded=[]
    parsed_modules=0
    eligible=set(imports)
    for name,paths in sorted(groups.items()):
        raw,status,_=witness.select_matching_module(paths,reader=witness.read)
        if raw is None:
            discarded.append({"module":name,"reason":status})
            continue
        parsed_modules+=1
        exported,has_section=module_export_strings(raw)
        if not has_section:
            no_ksymtab.append(name)
        for symbol in exported & eligible:
            providers[symbol].add(name)
    # The live kallsyms export symbol NAMES are additional *unattributed*
    # evidence. They are not addresses and do not prove vmlinux ownership.
    kallsyms_names,kallsyms_visible=(set(),False)
    if args.offline_dir is None:
        kallsyms_names,kallsyms_visible=observed_export_names_from_kallsyms(witness.read)
    found_in_modules={sym for sym,names in providers.items() if names}
    no_module_provider=set(imports)-found_in_modules
    unresolved=no_module_provider-kallsyms_names
    ksymtab_unattributed=no_module_provider&kallsyms_names
    result={
      "classification":"PRIVATE LOCAL IMPORT/EXPORT NAME ASSOCIATIONS, NOT VERIFIED ABI CRC OR LIVE KERNEL EXPORTS",
      "timestamp_utc":datetime.now(timezone.utc).isoformat(),
      "running_kernel":os.uname().release,
      "source_stock_inventory_name_count":len(imports),
      "module_path_count":len(paths),
      "unique_module_elfs_parsed":parsed_modules,
      "module_ELFs_without_ksymtab_strings":len(no_ksymtab),
      "module_ELFs_without_ksymtab_strings_sample":sorted(no_ksymtab)[:15],
      "module_names_skipped":discarded[:20],
      "skipped_module_count":len(discarded),
      "possible_provider_export_name_found_in_loaded_stock_module_ELF":len(found_in_modules),
      "multiple_possible_module_exporters":sum(len(p)>1 for p in providers.values()),
      "non_public_import_name_visible_in_live_ksymtab_but_not_candidate_modules":len(ksymtab_unattributed),
      "non_public_import_name_unresolved":len(unresolved),
      "kallsyms_has_any_ksymtab_names":kallsyms_visible,
      "possible_module_export_providers":{k:sorted(v) for k,v in sorted(providers.items())},
      "live_ksymtab_name_unattributed":sorted(ksymtab_unattributed),
      "not_yet_attributed_symbol_names":sorted(unresolved),
      "two_AR9271_known_gki_missing_exports":{
          s:{"name_seen_in_stock_module_export_section":s in providers,
             "module_exporter_candidates":sorted(providers.get(s,set())),
             "name_seen_in_live_ksymtab":s in kallsyms_names,
             "live_vmlinux_export_proven":False} for s in REMAINING
      },
      "limitations":[
        "A name in __ksymtab_strings proves only candidate ELF contains an export name, not that the exact on-disk module is loaded or the required CRC matches.",
        "Loaded-module imports and candidate-module export strings are not authoritative evidence of live vmlinux exports.",
        "Kallsyms __ksymtab_* entries can belong to built-in kernel or stock modules; this audit does not attribute their owner.",
        "Unattributed names can be exported from unloaded or inaccessible modules, vendor-built-in vmlinux, or excluded by the original symbol whitelist.",
        "The original Motorola abi_symbollist.raw is unavailable; do not append all non-GKI imported names to the KMI whitelist.",
        "Vendor-stock complete module signing/CFI and KernelSU compatibility and AR9271 hardware tests are unverified; no insmod, flash or boot image."
      ],
    }
    os.umask(0o077)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    fd=os.open(args.output,os.O_WRONLY|os.O_CREAT|os.O_TRUNC,0o600)
    with os.fdopen(fd,"w",encoding="utf-8") as f:
        json.dump(result,f,indent=2)
        f.write("\n")
    os.chmod(args.output,0o600)
    print("NEVADA STOCK MODULE PROVIDER ATTRIBUTION — READ ONLY / NOT INSTALLABLE")
    print("Input stock imports not in public GKI:",len(imports))
    print("Unique stock module ELF files examined:",parsed_modules)
    print("Stock candidate ELF modules lacking __ksymtab_strings:",len(no_ksymtab))
    print("Possible provider module exports for non-public import names:",len(found_in_modules))
    print("Names visible in live ksymtab but not matched to stock module export sections:",len(ksymtab_unattributed))
    print("Still unattributed non-public import names:",len(unresolved))
    print("Known two AR9271 blocker exports:",result["two_AR9271_known_gki_missing_exports"])
    print("Locally stored name-level report:",args.output)
    print("Export presence does NOT certify provider CRC, module loading, stock KMI or safety.")
    print("DO NOT install or flash the experimental Atheros drivers.")
    return result

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--stock-import-report",type=Path,required=True)
    p.add_argument("--stock-inventory-script",type=Path,required=True)
    p.add_argument("--output",type=Path,required=True)
    p.add_argument("--offline-dir",type=Path,help="CI synthetic ELF fixture; no root access")
    run(p.parse_args())

if __name__=="__main__":
    main()
